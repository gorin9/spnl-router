# spnl-router: ビルド時 ROUTES → 静的 dispatch ジェネレータ
#
# 入力: controller .rb (人が書く)
#   class BlogController
#     ROUTES = {
#       "/"          => :index,
#       "/about"     => :about,
#       "/posts/:id" => :show
#     }
#     def index;      ...; end
#     def about;      ...; end
#     def show(id);   ...; end
#   end
#
# 出力: router.generated.rb (Spinel-friendly な静的 case dispatch)
#   module Router
#     def self.dispatch(path)
#       c = BlogController.new
#       case path
#       when "/"      then c.set_chrome("home", c.index)
#       when "/about" then c.set_chrome("about", c.about)
#       else
#         if path.start_with?("/posts/")
#           id = path[7, path.length].to_i
#           c.set_chrome("home", c.show(id))
#         else
#           return "404"
#         end
#       end
#       c.render_layout
#     end
#   end

module SpnlRouter
  VERSION = "0.1.0"

  # path -> route entry
  Route = Struct.new(:path, :action, :nav, :param_name, :param_offset)

  def self.parse(source)
    # ROUTES = { ... } block を抽出
    m = source.match(/ROUTES\s*=\s*\{(.+?)\}/m)
    raise "no ROUTES hash found" unless m

    body = m[1]
    routes = []

    # "/path" => :action[, nav: "home"] の各エントリ
    body.scan(/"([^"]+)"\s*=>\s*:(\w+)(?:\s*,\s*nav:\s*"([^"]+)")?/) do |path, action, nav|
      r = Route.new(path, action.to_sym, nav, nil, nil)
      # :id のような param がある場合, prefix と offset を保存
      if path.include?(":")
        prefix = path.split(":")[0]
        param  = path.split(":")[1]
        r.param_name = param
        r.param_offset = prefix.length
        r.path = prefix
      end
      routes << r
    end

    # controller class 名を抽出
    cm = source.match(/class\s+(\w+)/)
    raise "no class found" unless cm
    controller_name = cm[1]

    [controller_name, routes]
  end

  def self.generate(source, target_module: "Router")
    controller_name, routes = parse(source)

    static_routes = routes.reject { |r| r.param_name }
    param_routes  = routes.select { |r| r.param_name }

    static_cases = static_routes.map { |r|
      nav = r.nav || infer_nav(r.path)
      "    when #{r.path.inspect}\n" \
      "      body = c.#{r.action}; nav = #{nav.inspect}"
    }.join("\n")

    # param routes: else 節で if 連鎖
    param_branches = param_routes.map { |r|
      nav = r.nav || infer_nav(r.path)
      "      if path.start_with?(#{r.path.inspect})\n" \
      "        #{r.param_name} = path[#{r.param_offset}, path.length].to_i\n" \
      "        body = c.#{r.action}(#{r.param_name}); nav = #{nav.inspect}\n" \
      "      end"
    }.join("\n      els")

    else_clause = if param_routes.empty?
      "    else\n      return \"404\""
    else
      "    else\n#{param_branches}\n      return \"404\" if body == \"\""
    end

    <<~RUBY
      # AUTO-GENERATED by spnl-router — DO NOT EDIT
      # source: #{controller_name}
      module #{target_module}
        def self.dispatch(path)
          c = #{controller_name}.new
          body = ""
          nav  = ""
          case path
      #{static_cases}
      #{else_clause}
          end
          c.set_chrome(nav, body)
          c.render_layout
        end
      end
    RUBY
  end

  def self.infer_nav(path)
    return "home" if path == "/"
    seg = path.split("/").reject(&:empty?).first
    seg.to_s
  end
end
